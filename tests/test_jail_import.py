def _concurrent_record_write(kind, path, started, finished):
    """Load stale state before waiting for the other process's transaction."""
    from klay.qt.library import GameLibrary

    path = Path(path)
    data = json.loads(path.read_text(encoding="utf-8"))
    library = GameLibrary.__new__(GameLibrary)
    game = GameEntry(path, data)
    started.set()
    if kind == "import":
        data["executable"] = "refreshed-source-command"
        import_worker._write_game(path.parent, data)
    else:
        library.set_hidden(game, True)
    finished.set()


class JailImportTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        # shared.py is generated by Meson and configures GLib/GSettings. Here
        # only its data directory is needed; keep all imports inside temp data.
        self.shared = types.ModuleType("klay.shared")
        self.shared.data_dir = self.root
        self.settings = Mock()
        self.settings.source_enabled.return_value = True
        self.settings.get_bool.side_effect = lambda key, default=False: default
        self.settings.get_state_bool.side_effect = lambda key, default=False: default
        self.path = self.root / "klay" / "games" / "steam_100.json"
        self.path.parent.mkdir(parents=True)
        self.config = {
            "enabled": True,
            "game_dir": "/home/player/Game",
            "exe": "game.exe",
            "runner_type": "wine",
            "runner": "/usr/bin/wine",
            "arguments": ["literal $(do-not-run)", "two words"],
        }

    def seed(self, config: object) -> None:
        self.path.write_text(
            json.dumps({
                "game_id": "steam_100", "name": "Original title", "source": "steam",
                "executable": "xdg-open steam://rungameid/100", "removed": False,
                "last_played": 123, "added": 100, "jail": config,
            }),
            encoding="utf-8",
        )

    def read_game(self) -> dict:
        return json.loads(self.path.read_text(encoding="utf-8"))

    def run_scan(self, names: list[str]) -> dict:
        class Source:
            source_id = "steam"
            is_available = True

            def __iter__(self):
                for name in names:
                    yield import_worker.FakeGame({
                        "game_id": "steam_100", "name": name, "source": "steam",
                        "executable": "new-source-launcher --game 100",
                    })

        with (
            patch.dict(sys.modules, {"klay.shared": self.shared}),
            patch.object(klay, "shared", self.shared, create=True),
            patch.dict(os.environ, {
                "KLAY_IMPORT_MODE": "import", "KLAY_IMPORT_FAST": "1",
                "KLAY_DATA_DIR_NAME": "klay",
            }),
            patch.object(import_worker, "SettingsBackend", return_value=self.settings),
            patch.object(import_worker, "_load_source_classes", return_value=[Source]),
            patch.object(import_worker, "_emit_progress"),
            patch.object(import_worker, "_attempt_cover_update", return_value=(False, False)),
        ):
            return import_worker._run_import()

    def test_jail_survives_route_refresh_rename_removal_and_readdition(self) -> None:
        self.seed(self.config)
        summary = self.run_scan(["Original title"])
        self.assertFalse(summary["errors"])
        self.assertEqual(summary["duplicates"], 1)
        self.assertEqual(self.read_game()["executable"], "new-source-launcher --game 100")
        self.assertEqual(self.read_game()["jail"], self.config)

        # A stable source ID may receive a substantially different display name.
        # This deliberately takes the importer's new-identity rebuild branch.
        summary = self.run_scan(["New title from the store"])
        self.assertEqual(summary["imported"], 1)
        self.assertEqual(self.read_game()["name"], "New title from the store")
        self.assertEqual(self.read_game()["jail"], self.config)

        summary = self.run_scan([])
        self.assertEqual(summary["removed"], 1)
        self.assertTrue(self.read_game()["removed"])
        self.assertEqual(self.read_game()["jail"], self.config)

        summary = self.run_scan(["Another store title"])
        self.assertFalse(summary["errors"])
        self.assertEqual(summary["imported"], 1)
        restored = self.read_game()
        self.assertFalse(restored["removed"])
        self.assertEqual(restored["jail"], self.config)
        self.assertTrue(GameEntry(self.path, restored).jail_enabled)

    def test_import_preserves_invalid_isolation_settings_for_fail_closed_validation(self) -> None:
        for raw_config in (None, "invalid", {"enabled": "false"}):
            with self.subTest(config=raw_config):
                self.seed(raw_config)
                summary = self.run_scan(["Renamed game"])
                self.assertFalse(summary["errors"])
                restored = self.read_game()
                self.assertIn("jail", restored)
                self.assertEqual(restored["jail"], raw_config)
                self.assertTrue(GameEntry(self.path, restored).jail_enabled)

    def test_jail_enabled_during_import_survives_each_write_path(self) -> None:
        original = import_worker._write_game
        for names in (["Original title"], ["Renamed title"], []):
            with self.subTest(names=names):
                self.seed({"enabled": False})

                def user_enables_before_import_commit(directory, data):
                    from klay.qt.library import GameLibrary

                    library = GameLibrary.__new__(GameLibrary)
                    current = GameEntry(self.path, self.read_game())
                    current.set_value("jail", self.config)
                    library.save_game(current)
                    original(directory, data)

                with patch.object(import_worker, "_write_game", side_effect=user_enables_before_import_commit):
                    summary = self.run_scan(names)
                self.assertFalse(summary["errors"])
                self.assertEqual(self.read_game()["jail"], self.config)

    def test_import_and_ui_writes_serialize_and_merge_current_user_fields(self) -> None:
        self.seed({"enabled": False})
        context = multiprocessing.get_context("spawn")
        workers = []
        try:
            with game_file_lock(self.path):
                for kind in ("import", "hide"):
                    started, finished = context.Event(), context.Event()
                    process = context.Process(
                        target=_concurrent_record_write,
                        args=(kind, str(self.path), started, finished),
                    )
                    process.start()
                    workers.append((process, finished))
                    self.assertTrue(started.wait(10))
                    self.assertFalse(finished.wait(.1), "Writer bypassed the metadata lock")
                # Model the user transaction that owns the lock. Both workers
                # have already read the preceding disabled-jail snapshot.
                current = self.read_game()
                current.update(jail=self.config, last_played=98765)
                self.path.write_text(json.dumps(current), encoding="utf-8")
            for process, finished in workers:
                process.join(10)
                self.assertEqual(process.exitcode, 0)
                self.assertTrue(finished.is_set())
            stored = self.read_game()
            self.assertEqual(stored["jail"], self.config)
            self.assertEqual(stored["last_played"], 98765)
            self.assertTrue(stored["hidden"])
            self.assertEqual(stored["executable"], "refreshed-source-command")
        finally:
            for process, _finished in workers:
                if process.is_alive():
                    process.terminate()
                process.join(5)


class JailCliTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        # Load the real CLI functions without a built schema, GUI, or host paths.
        shared = types.ModuleType("klay.shared")
        path = Path(import_worker.__file__).with_name("main.py")
        spec = importlib.util.spec_from_file_location("klay_jail_cli_test", path)
        assert spec is not None and spec.loader is not None
        cls.cli = importlib.util.module_from_spec(spec)
        with (
            patch.dict(sys.modules, {"klay.shared": shared}),
            patch.object(klay, "shared", shared, create=True),
        ):
            spec.loader.exec_module(cls.cli)

    def setUp(self) -> None:
        self.game = GameEntry(Path("steam_100.json"), {
            "game_id": "steam_100", "name": "Jailed game", "jail": {"enabled": True},
        })
        self.library = Mock()
        self.library.load_game_by_id.return_value = self.game
        self.library.launch.return_value.jail_warning = ""
        self.stderr = io.StringIO()

    def test_cli_returns_supervisor_failure_after_readiness(self) -> None:
        self.library.launch.return_value.wait.return_value = 7
        self.library.jail_report.return_value = {"status": "failed", "error": "Runner failed"}
        with redirect_stderr(self.stderr):
            result = self.cli._run_launch_mode(self.library, self.game.game_id)
        self.assertEqual(result, 7)
        self.library.launch.return_value.wait.assert_called_once_with()
        self.assertIn("Runner failed", self.stderr.getvalue())

    def test_cli_returns_failure_if_jail_setup_raises(self) -> None:
        self.library.launch.side_effect = JailError("Bubblewrap unavailable")
        with redirect_stderr(self.stderr):
            result = self.cli._run_launch_mode(self.library, self.game.game_id)
        self.assertEqual(result, 1)
        self.assertIn("Bubblewrap unavailable", self.stderr.getvalue())

    def test_cli_waits_for_successful_jailed_run(self) -> None:
        self.library.launch.return_value.wait.return_value = 0
        with redirect_stderr(self.stderr):
            result = self.cli._run_launch_mode(self.library, self.game.game_id)
        self.assertEqual(result, 0)
        self.library.launch.return_value.wait.assert_called_once_with()
        self.assertEqual(self.stderr.getvalue(), "")

    def test_cli_interrupt_stops_and_reaps_returned_jail_supervisor(self) -> None:
        process = self.library.launch.return_value
        process.wait.side_effect = KeyboardInterrupt
        with (
            patch.object(self.cli.jail, "stop_game") as stop_game,
            redirect_stderr(self.stderr),
        ):
            result = self.cli._run_launch_mode(self.library, self.game.game_id)
        self.assertEqual(result, 130)
        stop_game.assert_called_once_with(process)
        self.assertNotIn("Traceback", self.stderr.getvalue())

    def test_cli_interrupt_during_preparation_returns_without_a_second_stop(self) -> None:
        # The client owns and cleans up its process until launch returns it.
        self.library.launch.side_effect = KeyboardInterrupt
        with (
            patch.object(self.cli.jail, "stop_game") as stop_game,
            redirect_stderr(self.stderr),
        ):
            result = self.cli._run_launch_mode(self.library, self.game.game_id)
        self.assertEqual(result, 130)
        stop_game.assert_not_called()
        self.library.launch.return_value.wait.assert_not_called()
        self.assertNotIn("Traceback", self.stderr.getvalue())

    def test_cli_preserves_detached_ordinary_launch(self) -> None:
        self.game.data["jail"] = {"enabled": False}
        with (
            patch.object(self.cli.jail, "stop_game") as stop_game,
            redirect_stderr(self.stderr),
        ):
            result = self.cli._run_launch_mode(self.library, self.game.game_id)
        self.assertEqual(result, 0)
        self.library.launch.return_value.wait.assert_not_called()
        stop_game.assert_not_called()

    def test_cli_entry_restores_interrupt_cleanup_after_desktop_wrapper(self) -> None:
        previous = signal.getsignal(signal.SIGINT)
        try:
            signal.signal(signal.SIGINT, signal.SIG_DFL)
            self.library.launch.return_value.wait.return_value = 0
            with patch.object(self.cli, "GameLibrary", return_value=self.library):
                self.assertEqual(self.cli.main("test", ["--launch=" + self.game.game_id]), 0)
            self.assertIs(signal.getsignal(signal.SIGINT), signal.default_int_handler)
        finally:
            signal.signal(signal.SIGINT, previous)

    def test_cli_checks_graphics_without_launching_game(self) -> None:
        report = {'ok': True, 'graphics': {'opengl': {'status': 'passed'}}}
        self.library.check_jail.return_value = report
        output = io.StringIO()
        with patch.object(self.cli, 'GameLibrary', return_value=self.library), redirect_stdout(output):
            self.assertEqual(self.cli.main('test', ['--check-jail', self.game.game_id]), 0)
        self.library.check_jail.assert_called_once_with(self.game)
        self.library.launch.assert_not_called()
        self.assertEqual(json.loads(output.getvalue()), report)

    def test_cli_check_failure_reports_reason_without_launch(self) -> None:
        self.library.check_jail.side_effect = JailError('OpenGL graphics check failed')
        with patch.object(self.cli, 'GameLibrary', return_value=self.library), redirect_stderr(self.stderr):
            self.assertEqual(self.cli.main('test', ['--check-jail', self.game.game_id]), 1)
        self.library.launch.assert_not_called()
        self.assertIn('OpenGL graphics check failed', self.stderr.getvalue())

    def test_cli_rejects_check_and_launch_together(self) -> None:
        with patch.object(self.cli, 'GameLibrary', return_value=self.library), redirect_stderr(self.stderr):
            self.assertEqual(self.cli.main('test', ['--check-jail', 'one', '--launch', 'one']), 2)
        self.library.launch.assert_not_called()
        self.library.check_jail.assert_not_called()


if __name__ == "__main__":
    unittest.main()
